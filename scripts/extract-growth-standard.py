"""Generate verified WS/T 423-2022 age reference tables. No network required.

Usage: python extract_growth.py official.pdf output.js
Requires Poppler pdftotext and pdfplumber. Both independent extractions must agree.
"""
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path
import pdfplumber

MONTHS = list(range(25)) + list(range(27, 82, 3))
TABLES = [f'{appendix}.{number}' for appendix in ('A', 'B') for number in (1, 2, 3, 4, 9, 10)]

def parse(text):
    tables = {key: {} for key in TABLES}
    current = None
    for line in text.splitlines():
        heading = re.match(r'^\s*表\s*([AB])\s*\.\s*(\d+)\b', line)
        if heading:
            current = f'{heading[1]}.{heading[2]}'
        if current not in tables:
            continue
        row = re.fullmatch(r'\s*(.*?)\s+' + r'\s+'.join([r'(\d+\.\d+)'] * 7) + r'\s*', line)
        if not row:
            continue
        age = re.fullmatch(r'(?:(\d+)岁)?(?:(\d+)月)?', re.sub(r'\s', '', row[1]))
        if not age or not age[0]:
            continue
        month = int(age[1] or 0) * 12 + int(age[2] or 0)
        values = list(map(float, row.groups()[1:]))
        assert month not in tables[current], (current, month, 'duplicate')
        assert all(a < b for a, b in zip(values, values[1:])), (current, month)
        tables[current][month] = values
    for key, rows in tables.items():
        assert list(rows) == MONTHS, (key, len(rows), list(rows))
    return tables

pdf_path, output_path = map(Path, sys.argv[1:])
poppler = parse(subprocess.check_output(['pdftotext', '-layout', str(pdf_path), '-'], text=True))
with pdfplumber.open(pdf_path) as pdf:
    independent = parse('\n'.join(page.extract_text(x_tolerance=2) or '' for page in pdf.pages))
assert poppler == independent, 'Independent PDF extractions disagree; inspect before use.'
digest = hashlib.sha256(pdf_path.read_bytes()).hexdigest()
source = 'https://www.nhc.gov.cn/fzs/c100048/202211/5001d7cf57774770a1d49c1df46a291f/files/1733125082501_81468.pdf'
lines = ['// Generated by scripts/extract-growth-standard.py; do not edit numerical values by hand.',
         '// WS/T 423—2022, A.1–A.4, A.9–A.10, B.1–B.4, B.9–B.10. No interpolation.',
         f'export const assessmentSource = {json.dumps(source)};',
         f'export const assessmentPdfSha256 = {json.dumps(digest)};',
         '// A columns: P3,P10,P25,P50,P75,P90,P97. B: -3,-2,-1,median,+1,+2,+3 SD.',
         'export const assessmentTables = {']
for key, rows in poppler.items():
    lines.append(f'  "{key}": {{')
    for month, values in rows.items():
        lines.append(f'    {month}: {json.dumps(values, separators=(",", ":"))},')
    lines.append('  },')
lines.append('};\n')
output_path.write_text('\n'.join(lines))
print(f'Verified {len(TABLES)} tables, {len(TABLES)*len(MONTHS)} rows, {len(TABLES)*len(MONTHS)*7} thresholds. SHA256: {digest}')
